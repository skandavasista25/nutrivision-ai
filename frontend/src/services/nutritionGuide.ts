export interface FlatCard extends Card { sectionId: string; sectionLabel: string }
export const ALL_CARDS: FlatCard[] = SECTIONS.flatMap((s) => s.cards.map((c) => ({ ...c, sectionId: s.id, sectionLabel: s.label })));

/** Every word typed must appear somewhere in the card (title, summary, points, tags). */
export function searchCards(query: string, cards: FlatCard[] = ALL_CARDS): FlatCard[] {
  const words = query.toLowerCase().split(/[^a-z0-9]+/).filter((w) => w.length > 1);
  if (!words.length) return [];
  return cards.filter((c) => {
    const text = [c.title, c.summary, c.tags, ...c.points, ...(c.limit ?? []), c.ask ?? ""].join(" ").toLowerCase();
    return words.every((w) => text.includes(w));
  });
}

// ---- "Your daily needs" estimate for healthy adults ----
export type Activity = "sedentary" | "light" | "moderate" | "active";
export const ACTIVITY: Record<Activity, { factor: number; label: string }> = {
  sedentary: { factor: 1.2, label: "Sedentary (desk job, little exercise)" },
  light: { factor: 1.375, label: "Lightly active (light exercise 1 to 3 days a week)" },
  moderate: { factor: 1.55, label: "Moderately active (exercise 3 to 5 days a week)" },
  active: { factor: 1.725, label: "Very active (hard exercise most days or a physical job)" },
};
export interface NeedsInput { age: number; sex: "male" | "female"; weightKg: number; heightCm: number; activity: Activity; cerealHeavy: boolean }
export interface Needs { calories: number; protein: number; fatMax: number; satFatMax: number; sugarMax: number; saltMax: number; vegMin: number; fatGoal: number; carbGoal: number }

/** Rough estimate: Mifflin-St Jeor energy, protein at 0.83 g/kg (1 g/kg for cereal-heavy diets), limits from ICMR-NIN and WHO. Healthy adults only. */
export function estimateNeeds(i: NeedsInput): Needs | null {
  if (!(i.age >= 18 && i.age <= 100 && i.weightKg >= 30 && i.weightKg <= 250 && i.heightCm >= 120 && i.heightCm <= 230)) return null;
  const bmr = 10 * i.weightKg + 6.25 * i.heightCm - 5 * i.age + (i.sex === "male" ? 5 : -161);
  const calories = Math.max(1200, Math.round((bmr * ACTIVITY[i.activity].factor) / 10) * 10);
  const protein = Math.round(i.weightKg * (i.cerealHeavy ? 1 : 0.83));
  const fatGoal = Math.round((calories * 0.25) / 9);
  return {
    calories, protein, fatGoal,
    carbGoal: Math.max(1, Math.round((calories - protein * 4 - fatGoal * 9) / 4)),
    fatMax: Math.round((calories * 0.3) / 9), satFatMax: Math.round((calories * 0.1) / 9),
    sugarMax: Math.round((calories * 0.05) / 4), saltMax: 5, vegMin: 400,
  };
}